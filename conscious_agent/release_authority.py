def _digest(value: object) -> str:
    return hashlib.sha256(
        json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=True, default=str).encode("utf-8")
    ).hexdigest()


def _version_key(version: str) -> tuple[int, ...]:
    return tuple(int(part) for part in str(version).split("."))


def _visible_markdown(text: str) -> str:
    """Return the active portion before the collapsed legacy appendix."""
    marker = "<details id=\"retained-pre-v1250-compatibility\">"
    return text.split(marker, 1)[0]


def release_authority_record() -> dict[str, Any]:
    history = [
        {"version": version, "title": title, "ordinal": index}
        for index, (version, title) in enumerate(CHECKPOINT_HISTORY, 1)
    ]
    record: dict[str, Any] = {
        "contract_version": CONTRACT_VERSION,
        "schema_lineage_version": RELEASE_AUTHORITY_SCHEMA_VERSION,
        "working_source_version": WORKING_SOURCE_VERSION,
        "previous_working_source_version": PREVIOUS_WORKING_SOURCE_VERSION,
        "milestone": MILESTONE,
        "next_bounded_unit": NEXT_BOUNDED_UNIT,
        "codex_review_state": CODEX_REVIEW_STATE,
        "authoritative_baseline_archive_sha256": AUTHORITATIVE_BASELINE_ARCHIVE_SHA256,
        "history": history,
        "history_count": len(history),
        "history_chronological": [row["version"] for row in history]
        == sorted((row["version"] for row in history), key=_version_key),
        "legacy_document_hashes": dict(LEGACY_DOCUMENT_HASHES),
        "read_only": True,
        "content_free": True,
        **AUTHORITY_FLAGS,
    }
    record["authority_digest"] = _digest(record)
    return record


def _actual_assignment(text: str, name: str) -> str:
    match = re.search(rf"^{re.escape(name)}\s*=\s*[\"']([^\"']+)[\"']", text, flags=re.MULTILINE)
    return match.group(1) if match else ""


def _visible_history_versions(text: str) -> list[str]:
    visible = _visible_markdown(text)
    return re.findall(r"^## v([0-9]+(?:\.[0-9]+)+)\b", visible, flags=re.MULTILINE)


def validate_release_authority(*, source_root: str | Path | None = None) -> dict[str, Any]:
    root = Path(source_root or Path(__file__).resolve().parents[1]).resolve()
    record = release_authority_record()
    paths = {
        name: root / name
        for name in (
            "README.md",
            "README_NEXT_STEPS.md",
            "README_RELEASE_HISTORY.md",
            "archive/docs/legacy_dependencies/roadmaps/README_V1100_ROADMAP.md",
            "release_metadata.py",
            "conscious_agent/release_metadata.py",
        )
    }
    texts = {name: path.read_text(encoding="utf-8") if path.is_file() else "" for name, path in paths.items()}
    visible_readme = _visible_markdown(texts["README.md"])
    visible_next = _visible_markdown(texts["README_NEXT_STEPS.md"])
    visible_history = _visible_markdown(texts["README_RELEASE_HISTORY.md"])
    visible_roadmap = _visible_markdown(texts["archive/docs/legacy_dependencies/roadmaps/README_V1100_ROADMAP.md"])
    versions = _visible_history_versions(texts["README_RELEASE_HISTORY.md"])

    # Post-v2503.2 documentation cleanup retired the active roadmap from the
    # repository root and hash-preserved it beneath archive/docs.  Release
    # authority must not require mutating that historical artifact merely to
    # carry the current version marker; the three active root ledgers own the
    # current release-facing source state.
    roadmap_retired_by_policy = False
    archive_manifest_path = root / "archive/docs/DOCUMENT_ARCHIVE_MANIFEST.json"
    active_roadmap_path = root / "README_V1100_ROADMAP.md"
    if not active_roadmap_path.exists() and archive_manifest_path.is_file():
        try:
            archive_manifest = json.loads(archive_manifest_path.read_text(encoding="utf-8"))
            for move in archive_manifest.get("moves", []):
                if not isinstance(move, Mapping) or move.get("from") != "README_V1100_ROADMAP.md":
                    continue
                archived = root / str(move.get("to") or "")
                expected = str(move.get("sha256") or "")
                actual = hashlib.sha256(archived.read_bytes()).hexdigest() if archived.is_file() else ""
                roadmap_retired_by_policy = bool(expected and actual == expected)
                break
        except (OSError, ValueError, TypeError):
            roadmap_retired_by_policy = False

    legacy_checks = {}
    for relative, expected in LEGACY_DOCUMENT_HASHES.items():
        path = root / relative
        actual = hashlib.sha256(path.read_bytes()).hexdigest() if path.is_file() else ""
        legacy_checks[relative] = actual == expected

    checks = {
        "authority_history_chronological": record["history_chronological"] is True,
        "active_readme_version": bool(re.search(
            rf"Current source:\s+(?:\*\*)?v{re.escape(WORKING_SOURCE_VERSION)}\b", visible_readme,
        )),
        "active_next_steps_version": bool(re.search(
            rf"Current source:\s+(?:\*\*)?v{re.escape(WORKING_SOURCE_VERSION)}\b", visible_next,
        )),
        "active_roadmap_version": roadmap_retired_by_policy or bool(re.search(
            rf"Current source:\s+(?:\*\*)?v{re.escape(WORKING_SOURCE_VERSION)}\b", visible_roadmap,
        )),
        "single_next_steps_h1": len(re.findall(r"^# ", visible_next, flags=re.MULTILINE)) == 1,
        "codex_review_postponed": CODEX_REVIEW_STATE in visible_next,
        "next_bundle_named": NEXT_BOUNDED_UNIT in visible_next,
        # Release notes conventionally place the newest active entry first. The
        # retained historical appendix is separately immutable and excluded.
        "history_visible_chronological": versions[:1] == [WORKING_SOURCE_VERSION] and len(versions) == len(set(versions)),
        "history_contains_current": WORKING_SOURCE_VERSION in versions,
        "history_contains_baseline": "1249.9" in versions,
        "agent_metadata_current": _actual_assignment(texts["conscious_agent/release_metadata.py"], "WORKING_SOURCE_VERSION") == WORKING_SOURCE_VERSION,
        "agent_metadata_previous": _actual_assignment(texts["conscious_agent/release_metadata.py"], "PREVIOUS_WORKING_SOURCE_VERSION") == PREVIOUS_WORKING_SOURCE_VERSION,
        "top_metadata_current": f"Active source marker: {WORKING_SOURCE_VERSION}" in texts["release_metadata.py"],
        "legacy_archives_immutable": all(legacy_checks.values()),
        "visible_history_not_legacy_dump": "Current source: v1190.9" not in visible_history,
        "visible_readme_not_stale": "Current source: v1219.9" not in visible_readme,
        "visible_next_not_stale": "Current source: v1249.9" not in visible_next,
    }
    passed = sum(bool(value) for value in checks.values())
    result = {
        "ok": passed == len(checks),
        "status": "release_authority_consistent" if passed == len(checks) else "release_authority_blocked",
        "contract_version": CONTRACT_VERSION,
        "working_source_version": WORKING_SOURCE_VERSION,
        "previous_working_source_version": PREVIOUS_WORKING_SOURCE_VERSION,
        "checks": checks,
        "passed": passed,
        "total": len(checks),
        "visible_history_versions": versions,
        "legacy_archive_checks": legacy_checks,
        "read_only": True,
        "content_free": True,
        **AUTHORITY_FLAGS,
    }
    result["validation_digest"] = _digest(result)
    return result


