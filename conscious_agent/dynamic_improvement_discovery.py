"""Provider-free, read-only discovery of bounded source improvement families.

v1490.0-v1490.2 deliberately stops at structural discovery.  It inventories
source, records content-free evidence, describes zero or more candidate
families, and rejects unsafe/weak families.  It does not rank, select, persist,
prepare, approve, implement, install, promote, or contact a provider.
"""

