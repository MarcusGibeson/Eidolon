def build_dynamic_improvement_discovery(
    source_root: str | Path,
    *,
    completed_lineages: Iterable[Mapping[str, Any]] | None = None,
) -> dict[str, Any]:
    """Describe credible structural opportunities without selecting or mutating anything."""
    started = time.perf_counter()
    root = Path(source_root).expanduser().resolve()
    lineage_rows = [dict(row or {}) for row in completed_lineages or ()]
    source_shape = _source_shape_fingerprint(root)
    root_key = str(root)
    prior_shape = _LAST_SOURCE_SHAPE.get(root_key)
    cache_key = _digest({
        "schema_version": DISCOVERY_SCHEMA_VERSION,
        "source_shape": source_shape,
        "completed_lineages": lineage_rows,
    })
    cached = _DISCOVERY_CACHE.get(cache_key) if prior_shape == source_shape else None
    _LAST_SOURCE_SHAPE[root_key] = source_shape
    if cached is not None:
        restored = copy.deepcopy(cached)
        restored["cache_hit"] = True
        restored["discovery_elapsed_ms"] = round((time.perf_counter() - started) * 1000.0, 3)
        return restored
    inventory = build_python_ast_inventory(root)
    completed_destinations, completed_symbols, completed_digests = _lineage_sets(lineage_rows)
    discovered: list[dict[str, Any]] = []
    for module in inventory["modules"]:
        discovered.extend(_discover_module_families(
            root,
            module,
            completed_destinations=completed_destinations,
            completed_symbols=completed_symbols,
            completed_digests=completed_digests,
        ))
    discovered.sort(key=lambda row: (str(row["source_module"]), int(row["symbol_spans"][0][1]), str(row["candidate_id"])))
    eligible = [row for row in discovered if row["eligible_for_later_planning"]]
    rejected = [row for row in discovered if not row["eligible_for_later_planning"]]
    focus_module = "conscious_agent/self_maintenance.py"
    focus_candidates = [row for row in eligible if row["source_module"] == focus_module]
    focus_rejections = [row for row in rejected if row["source_module"] == focus_module]
    focus_inventory = next((row for row in inventory["modules"] if row["module"] == focus_module), None)
    all_symbols = [symbol for module in inventory["modules"] for symbol in module.get("symbols") or []]
    symbol_exclusion_counts = {
        "retained_extraction_wrapper": sum(bool(item.get("retained_extraction_wrapper")) for item in all_symbols),
        "dependency_factory": sum(bool(item.get("dependency_factory")) for item in all_symbols),
        "generated_wrapper": sum(bool(item.get("generated_wrapper")) for item in all_symbols),
        "protected_authority_name": sum(bool(item.get("protected_authority_boundary")) for item in all_symbols),
    }
    source_unchanged = verify_inventory_source_unchanged(root, inventory)
    result = {
        "schema_version": DISCOVERY_SCHEMA_VERSION,
        "state": "discovery_candidates_available" if eligible else "no_qualifying_candidate",
        "inventory_digest": inventory["inventory_digest"],
        "module_count": inventory["module_count"],
        "symbol_count": inventory["symbol_count"],
        "parse_failure_count": inventory["parse_failure_count"],
        "eligible_candidate_count": len(eligible),
        "rejected_candidate_count": len(rejected),
        "candidate_count_returned": min(len(eligible), MAX_PUBLIC_CANDIDATES),
        "rejection_count_returned": min(len(rejected), MAX_PUBLIC_REJECTIONS),
        "candidates_truncated": len(eligible) > MAX_PUBLIC_CANDIDATES,
        "rejections_truncated": len(rejected) > MAX_PUBLIC_REJECTIONS,
        "candidates": eligible[:MAX_PUBLIC_CANDIDATES],
        "rejected_candidates": rejected[:MAX_PUBLIC_REJECTIONS],
        "focus_module": focus_module,
        "focus_module_summary": {
            "module": focus_module,
            "module_size_bytes": int((focus_inventory or {}).get("module_size_bytes") or 0),
            "line_count": int((focus_inventory or {}).get("line_count") or 0),
            "top_level_symbol_count": int((focus_inventory or {}).get("top_level_symbol_count") or 0),
            "retained_extraction_wrapper_count": sum(bool(item.get("retained_extraction_wrapper")) for item in (focus_inventory or {}).get("symbols") or []),
            "dependency_factory_count": sum(bool(item.get("dependency_factory")) for item in (focus_inventory or {}).get("symbols") or []),
        },
        "focus_candidates": focus_candidates[:8],
        "focus_rejections": focus_rejections[:16],
        "symbol_exclusion_counts": symbol_exclusion_counts,
        "completed_lineage_count": len(lineage_rows),
        "selection_made": False,
        "ranking_performed": False,
        "workspace_prepared": False,
        "approval_requested": False,
        "provider_contacted": False,
        "source_modified": False,
        "runtime_modified": False,
        "private_runtime_scanned": False,
        "source_unchanged": source_unchanged,
        "cache_hit": False,
        "discovery_elapsed_ms": round((time.perf_counter() - started) * 1000.0, 3),
        "content_free": True,
    }
    result["discovery_digest"] = _digest({
        "schema_version": DISCOVERY_SCHEMA_VERSION,
        "inventory_digest": result["inventory_digest"],
        "candidates": [(row["candidate_id"], row["evidence_digest"]) for row in eligible],
        "rejected": [(row["candidate_id"], tuple(row["rejection_codes"])) for row in rejected],
        "completed_destinations": sorted(completed_destinations),
        "completed_symbols": sorted(completed_symbols),
    })
    if len(_DISCOVERY_CACHE) >= _DISCOVERY_CACHE_LIMIT:
        _DISCOVERY_CACHE.pop(next(iter(_DISCOVERY_CACHE)))
    _DISCOVERY_CACHE[cache_key] = copy.deepcopy(result)
    return result


